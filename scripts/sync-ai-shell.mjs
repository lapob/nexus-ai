// Keep the edge fallback identical to the public AI shell, without user data.
import { createRequire } from 'node:module';
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const require = createRequire(import.meta.url);
const sourceRoot = process.argv.find(value => value.startsWith('--source-root='))?.slice('--source-root='.length)
  || fileURLToPath(new URL('../../.AI/', import.meta.url));
const { PUBLIC_AI_HTML } = require(resolve(sourceRoot, 'src/remote/remote-session-gateway.js'));
await writeFile(new URL('../worker/public-ai-shell.ts', import.meta.url), '// Generated by scripts/sync-ai-shell.mjs from the canonical public UI.\nexport const publicAiShell = ' + JSON.stringify(PUBLIC_AI_HTML) + ';\n');
console.log('Public AI edge shell synchronized.');
