// Keep the edge fallback identical to the public AI shell, without user data.
import { createRequire } from 'node:module';
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const require = createRequire(import.meta.url);
const sourceRoot = process.argv.find(value => value.startsWith('--source-root='))?.slice('--source-root='.length)
  || fileURLToPath(new URL('../../.AI/', import.meta.url));
const { PUBLIC_AI_HTML, PUBLIC_AI_BUILT, PUBLIC_AI_MANIFEST, PUBLIC_AI_SERVICE_WORKER } = require(resolve(sourceRoot, 'src/remote/remote-session-gateway.js'));
if (![PUBLIC_AI_HTML, PUBLIC_AI_MANIFEST, PUBLIC_AI_SERVICE_WORKER].every(value => typeof value === 'string' && value.length)) throw new Error('Canonical AI artifacts missing');
// The source exposes a maintenance page when web-dist is missing: never ship it to the edge.
if (PUBLIC_AI_BUILT !== true) throw new Error('Build the AI web app first (npm run build:web in the AI source root).');
await writeFile(new URL('../worker/public-ai-shell.ts', import.meta.url), '// Generated by scripts/sync-ai-shell.mjs from the canonical public UI.\n'
  + `export const publicAiShell = ${JSON.stringify(PUBLIC_AI_HTML)};\n`
  + `export const publicAiManifest = ${JSON.stringify(PUBLIC_AI_MANIFEST)};\n`
  + `export const publicAiServiceWorker = ${JSON.stringify(PUBLIC_AI_SERVICE_WORKER)};\n`);
console.log('Public AI edge shell synchronized.');
