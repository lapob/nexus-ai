// Keep the site's particle field on the same versioned core as the AI app: copies the canonical shared module
// (`.AI/web/src/nexus-core.ts`) into `app/components/nexus-core.ts` with its version and SHA-256 in the header.
// `--check` only verifies that the copy is current (used by tests when the AI source is next to the site).
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const sourceRoot = process.argv.find(value => value.startsWith('--source-root='))?.slice('--source-root='.length)
  || fileURLToPath(new URL('../../.AI/', import.meta.url));
const check = process.argv.includes('--check');
const source = (await readFile(new URL('web/src/nexus-core.ts', `file:///${sourceRoot.replace(/\\/g, '/').replace(/\/?$/, '/')}`), 'utf8')).replace(/\r\n/g, '\n');
const version = /export const NEXUS_CORE_VERSION = '(\d+\.\d+\.\d+)';/.exec(source)?.[1];
if (!version) throw new Error('Canonical core version missing');
if (/^import /m.test(source)) throw new Error('The shared core must not have dependencies');
const digest = createHash('sha256').update(source).digest('hex');
const header = `// Generated by scripts/sync-nexus-core.mjs from the AI source. Do not edit: change the canonical module.\n// nexus-core ${version} sha256:${digest}\n`;
const target = new URL('../app/components/nexus-core.ts', import.meta.url);
const expected = header + source;
if (check) {
  const current = await readFile(target, 'utf8').catch(() => '');
  if (current.replace(/\r\n/g, '\n') !== expected) { console.error(`nexus-core is stale: run node scripts/sync-nexus-core.mjs (canonical ${version}).`); process.exit(1); }
  console.log(`nexus-core ${version} is current.`);
} else {
  await writeFile(target, expected);
  console.log(`nexus-core ${version} synchronized (sha256 ${digest.slice(0, 12)}).`);
}
