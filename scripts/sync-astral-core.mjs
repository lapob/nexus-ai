// The renderer is authored once in the AI repository. Keep the checked-in
// standalone site copy so a site-only checkout builds without server sources.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
const root = resolve(import.meta.dirname, '..');
const source = await readFile(resolve(root, '../.AI/src/shared/astral-core.js'), 'utf8');
const output = '// Generated by scripts/sync-astral-core.mjs — edit the canonical AI renderer.\n'
  + source.replace('function createAstralCore(', 'export function createAstralCore(').replace(/\nmodule\.exports = \{ createAstralCore \};\s*$/, '\n');
await mkdir(resolve(root, 'app/lib'), {recursive:true});
await writeFile(resolve(root, 'app/lib/astral-core.js'), output);
console.log('Astral renderer synchronized.');
